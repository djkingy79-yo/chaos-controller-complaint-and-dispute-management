export function buildAuditTrailSections(caseItem, evidence, events, emailLogs) {
  const entries = [];
  const push = (date, label) => { if (date) entries.push({ date: new Date(date), label }); };
  push(caseItem.created_date, "Case created");
  push(caseItem.updated_date, "Case last updated");
  (evidence || []).forEach(ev => push(ev.created_date, `Evidence uploaded: ${ev.file_name}`));
  (events || []).forEach(ev => push(ev.created_date, `Timeline event recorded: ${ev.title}`));
  Object.entries(LETTER_FIELD_MAP).forEach(([key, field]) => {
    const sentField = LETTER_SENT_FIELD_MAP[key];
    if (caseItem[sentField]) push(caseItem[sentField], `${LETTER_LABELS[key]} letter marked sent${caseItem.letter_tracking?.[key]?.manuallyMarkedSent ? " (retrospective entry)" : ""}`);
  });
  (emailLogs || []).forEach(e => push(e.sent_at || e.created_date, `Email sent: "${e.subject}" to ${e.recipient_email} [${e.status}]`));
  if (caseItem.escalated_at) push(caseItem.escalated_at, "Escalation unlocked / case escalated");

  const sorted = entries.filter(e => e.date && !isNaN(e.date)).sort((a, b) => a.date - b.date);
  return [{
    heading: `Audit Trail (${sorted.length} recorded actions)`,
    paragraphs: ["Derived from the case, evidence, timeline, letter and email records held by Chaos Controller. This reflects the timestamped records available for this case, not a dedicated system audit log."],
    bullets: sorted.length ? sorted.map(e => `${format(e.date, "d MMM yyyy, h:mm a")} — ${e.label}`) : undefined,
    empty: "No recorded actions found.",
  }];
}

export function buildLegislationSections(caseItem) {
  const list = getRelevantLegislation(caseItem);
  return [{
    heading: "Legislation & Authorities Relevant to This Case",
    bullets: list.map(l => `${l.law} — ${l.why}`),
  }];
}

export function buildStatisticsSections(caseItem, evidence, events, deadlines, merchantResponses, emailLogs) {
  const now = new Date();
  const caseAgeDays = caseItem.created_date ? differenceInDays(now, new Date(caseItem.created_date)) : null;
  const lettersGenerated = Object.values(LETTER_FIELD_MAP).filter(f => caseItem[f]).length;
  const lettersSent = Object.values(LETTER_SENT_FIELD_MAP).filter(f => caseItem[f]).length;
  const completedDeadlines = (deadlines || []).filter(d => d.status === "completed").length;
  const outstandingDeadlines = (deadlines || []).filter(d => d.status === "pending").length;

  const responseTimes = [];
  [
    [caseItem.first_complaint_sent_at, caseItem.first_response_received_at],
    [caseItem.second_complaint_sent_at, caseItem.second_response_received_at],
    [caseItem.third_complaint_sent_at, caseItem.third_response_received_at],
  ].forEach(([sent, received]) => { if (sent && received) responseTimes.push(differenceInDays(new Date(received), new Date(sent))); });
  const avgResponseDays = responseTimes.length ? Math.round(responseTimes.reduce((a, b) => a + b, 0) / responseTimes.length) : null;
  const timeToEscalation = caseItem.first_complaint_sent_at && caseItem.escalated_at
    ? differenceInDays(new Date(caseItem.escalated_at), new Date(caseItem.first_complaint_sent_at))
    : null;

  return [{
    heading: "Case Statistics",
    rows: [
      { label: "Case Age", value: caseAgeDays !== null ? `${caseAgeDays} days` : null },
      { label: "Evidence Files Uploaded", value: String((evidence || []).length) },
      { label: "Letters Generated", value: `${lettersGenerated} of 6` },
      { label: "Letters Sent", value: `${lettersSent} of 6` },
      { label: "Responses Received", value: String((merchantResponses || []).length) },
      { label: "Timeline Events", value: String((events || []).length) },
      { label: "Emails Sent", value: String((emailLogs || []).length) },
      { label: "Deadlines Completed", value: String(completedDeadlines) },
      { label: "Deadlines Outstanding", value: String(outstandingDeadlines) },
      { label: "Average Response Time", value: avgResponseDays !== null ? `${avgResponseDays} days` : "Not yet available" },
      { label: "Time to Escalation", value: timeToEscalation !== null ? `${timeToEscalation} days` : "Not yet escalated" },
    ],
  }];
}