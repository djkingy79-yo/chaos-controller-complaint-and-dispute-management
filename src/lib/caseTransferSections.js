/**
 * CHAOS CONTROLLER — Case Transfer Package section builders.
 * Pure data functions producing ReportDocument-compatible section arrays
 * ({ heading, rows, paragraphs, bullets, empty }). No rendering or PDF logic
 * lives here — that all happens through ReportDocument + captureDocumentPDF.
 */

import { format, differenceInDays } from "date-fns";
import { LETTER_FIELD_MAP, LETTER_LABELS, LETTER_SENT_FIELD_MAP } from "@/lib/disputeStageLogic";
import { getRelevantLegislation } from "@/lib/legislationMapping";

const fmt = (d) => (d ? format(new Date(d), "d MMM yyyy") : null);

