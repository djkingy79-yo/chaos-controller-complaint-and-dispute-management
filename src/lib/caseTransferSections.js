export function buildTimelineSections(caseItem, events) {
  const derived = [];
  const push = (date, label) => { if (date) derived.push({ date: new Date(date), label }); };
  push(caseItem.created_date, "Case created");
  push(caseItem.first_complaint_sent_at, "1st Complaint Letter sent");
  push(caseItem.first_response_received_at, "Response received to 1st Complaint");
  push(caseItem.first_no_response_at, "No response recorded after 1st Complaint");
  push(caseItem.second_complaint_sent_at, "2nd Complaint Letter sent");
  push(caseItem.second_response_received_at, "Response received to 2nd Complaint");
  push(caseItem.second_no_response_at, "No response recorded after 2nd Complaint");
  push(caseItem.third_complaint_sent_at, "3rd/Final Complaint Letter sent");
  push(caseItem.third_response_received_at, "Response received to 3rd Complaint");
  push(caseItem.third_no_response_at, "No response recorded after 3rd Complaint");
  push(caseItem.accept_offer_sent_at, "Acceptance of Offer letter sent");
  push(caseItem.deny_offer_sent_at, "Rejection of Offer letter sent");
  push(caseItem.escalated_at, `Escalated to ${caseItem.escalation_body || "external body"}`);
  push(caseItem.final_outcome_at, "Final outcome recorded");

  const fromEvents = (events || []).map(ev => ({
    date: ev.event_date ? new Date(ev.event_date) : new Date(ev.created_date),
    label: `[${(ev.event_type || "event").replace(/_/g, " ").toUpperCase()}] ${ev.title}${ev.description ? " — " + ev.description : ""}`,
  }));

  const all = [...derived, ...fromEvents]
    .filter(e => e.date && !isNaN(e.date))
    .sort((a, b) => a.date - b.date);

  return [{
    heading: `Matter Timeline (${all.length} events)`,
    bullets: all.length ? all.map(e => `${format(e.date, "d MMM yyyy")} — ${e.label}`) : undefined,
    empty: "No timeline events recorded.",
  }];
}

export function buildWeeklySnapshotSections(caseItem, evidence, events, deadlines) {
  const now = new Date();
  const weekAgo = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);
  const twoWeeksAhead = new Date(now.getTime() + 14 * 24 * 60 * 60 * 1000);
  const recent = (events || []).filter(e => e.event_date && new Date(e.event_date) > weekAgo);
  const upcoming = (deadlines || []).filter(d => d.deadline_date && new Date(d.deadline_date) > now && new Date(d.deadline_date) < twoWeeksAhead && d.status === "pending");
  const overdue = (deadlines || []).filter(d => d.deadline_date && new Date(d.deadline_date) < now && d.status === "pending");
  const lettersDone = Object.values(LETTER_FIELD_MAP).filter(f => caseItem[f]).length;

  return [
    {
      heading: "This Week",
      rows: [
        { label: "Status", value: (caseItem.status || "").replace(/_/g, " ").toUpperCase() },
        { label: "New Timeline Events", value: String(recent.length) },
        { label: "Upcoming Deadlines (14 days)", value: String(upcoming.length) },
        { label: "Overdue Items", value: String(overdue.length) },
        { label: "Letters Completed", value: `${lettersDone} of 6` },
        { label: "Evidence Files", value: String((evidence || []).length) },
      ],
    },
    {
      heading: "Recent Activity",
      bullets: recent.length ? recent.map(e => `${fmt(e.event_date)} — ${e.title}`) : undefined,
      empty: "No new activity in the last 7 days.",
    },
    {
      heading: "Upcoming Deadlines",
      bullets: upcoming.length ? upcoming.map(d => `${d.title} — Due ${fmt(d.deadline_date)}`) : undefined,
      empty: "No deadlines in the next 14 days.",
    },
    {
      heading: "Recommended Next Action",
      paragraphs: [
        !caseItem.first_complaint_sent_at
          ? "Send the 1st Complaint Letter to open the formal dispute."
          : overdue.length
            ? "Address overdue deadlines before proceeding further."
            : "Continue monitoring for a response and prepare the next letter in the sequence if the deadline passes.",
      ],
    },
  ];
}

export function buildDeadlinesSections(deadlines) {
  const now = new Date();
  const sorted = [...(deadlines || [])].sort((a, b) => new Date(a.deadline_date || 0) - new Date(b.deadline_date || 0));
  const byMonth = {};
  sorted.forEach(d => {
    const key = d.deadline_date ? format(new Date(d.deadline_date), "MMMM yyyy") : "No Date";
    byMonth[key] = byMonth[key] || [];
    byMonth[key].push(d);
  });
  const calendarSections = Object.entries(byMonth).map(([month, items]) => ({
    heading: month,
    bullets: items.map(d => `${fmt(d.deadline_date) || "No date"} — ${d.title} (${(d.status || "").toUpperCase()})`),
  }));
  const chronoSection = {
    heading: `Chronological Deadline List (${sorted.length})`,
    bullets: sorted.length ? sorted.map(d => {
      const daysLeft = d.deadline_date ? differenceInDays(new Date(d.deadline_date), now) : null;
      const urgency = daysLeft === null ? "" : daysLeft < 0 ? ` [OVERDUE ${Math.abs(daysLeft)}d]` : daysLeft === 0 ? " [DUE TODAY]" : ` [${daysLeft}d left]`;
      return `${d.title} — Due ${fmt(d.deadline_date) || "no date"}${urgency} — ${(d.deadline_type || "").replace(/_/g, " ")} — ${(d.status || "").toUpperCase()}`;
    }) : undefined,
    empty: "No deadlines recorded.",
  };
  return [
    { heading: "Deadlines Calendar", paragraphs: ["Grouped by month below, followed by a full chronological list."] },
    ...calendarSections,
    chronoSection,
  ];
}

export function buildMerchantResponsesSections(responses) {
  const sorted = [...(responses || [])].sort((a, b) => new Date(a.created_date) - new Date(b.created_date));
  return [{
    heading: `Merchant / Organisation Responses (${sorted.length})`,
    bullets: sorted.length ? sorted.map(r =>
      `${fmt(r.created_date)} — ${r.merchant_name || r.merchant_email} [${(r.response_type || "").replace(/_/g, " ")}]${r.offer_amount ? " — Offer: " + r.offer_amount : ""} — ${r.response_text}`
    ) : undefined,
    empty: "No responses received via the app portal.",
  }];
}

export function buildEvidenceIndexSections(evidence) {
  const sorted = [...(evidence || [])].sort((a, b) => new Date(a.event_date || a.created_date) - new Date(b.event_date || b.created_date));
  return [{
    heading: `Evidence Index (${sorted.length})`,
    bullets: sorted.length ? sorted.map((ev, i) =>
      `${i + 1}. ${ev.file_name} — ${(ev.file_type || "other").replace(/_/g, " ")} — ${fmt(ev.event_date) || "no date"}${ev.description ? " — " + ev.description : (ev.extracted_data?.document_summary ? " — " + ev.extracted_data.document_summary : "")}`
    ) : undefined,
    empty: "No evidence files uploaded.",
  }];
}

export function buildEmailCorrespondenceSections(emailLogs) {
  const sorted = [...(emailLogs || [])].sort((a, b) => new Date(a.created_date) - new Date(b.created_date));
  return [{
    heading: `Email Correspondence (${sorted.length})`,
    bullets: sorted.length ? sorted.map(e =>
      `${e.sent_at ? format(new Date(e.sent_at), "d MMM yyyy, h:mm a") : fmt(e.created_date)} — To: ${e.recipient_email} — "${e.subject}" — [${(e.status || "").toUpperCase()}]${e.attachment_names?.length ? " — Attachments: " + e.attachment_names.join(", ") : ""}`
    ) : undefined,
    empty: "No emails sent via the app.",
  }];
}

export function buildNotesSections(caseItem, events) {
  const noteEvents = (events || []).filter(e => /note/i.test(e.event_type || ""));
  const trackingNotes = Object.entries(caseItem.letter_tracking || {}).filter(([, v]) => v?.sentNotes).map(([k, v]) => `${LETTER_LABELS[k] || k}: ${v.sentNotes}`);
  return [
    { heading: "Case Notes", paragraphs: [caseItem.notes], empty: "No manual notes recorded." },
    { heading: "Retrospective Sent-Date Notes", bullets: trackingNotes.length ? trackingNotes : undefined, empty: "No retrospective notes recorded." },
    { heading: "Timeline Notes", bullets: noteEvents.length ? noteEvents.map(e => `${fmt(e.event_date)} — ${e.title}${e.description ? ": " + e.description : ""}`) : undefined, empty: "No dedicated note-type timeline events." },
  ];
}

